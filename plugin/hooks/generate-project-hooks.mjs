import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdir,
  readFile,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HOOKS_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const PLUGIN_ROOT = resolve(HOOKS_DIRECTORY, "..");
const HOSTS = new Set(["cursor", "codex"]);
const CHECKER_FILES = [
  "dispatch.mjs",
  "pre-commit.mjs",
  "pre-rebase.mjs",
  "pre-pr-create.mjs",
  "pre-review-submit.mjs",
  "pre-pr-ready.mjs",
  "pre-merge.mjs",
  "post-merge.mjs",
];
const HELPER_FILES = [
  "lib/read-hook-input.mjs",
  "lib/run-command.mjs",
  "lib/run-command-worker.mjs",
];
const GENERATED_HEADER =
  "// CromeSDK generated by generate-project-hooks. Do not edit directly.";
const GENERATED_BLOCK_START =
  "<!-- BEGIN CromeSDK generated GitHub project hooks -->";
const GENERATED_BLOCK_END =
  "<!-- END CromeSDK generated GitHub project hooks -->";
const STATE_PATHS = {
  cursor: ".cursor/hooks/state/",
  codex: ".codex/hooks/state/",
};

const isRecord = (value) =>
  value !== null && typeof value === "object" && !Array.isArray(value);

const sha256 = (value) =>
  createHash("sha256").update(value).digest("hex");

const normalizeHostList = (value) => {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error("Missing --hosts. Expected cursor, codex, or both.");
  }

  const names = value
    .split(",")
    .map((name) => name.trim().toLowerCase())
    .filter(Boolean);
  if (names.length === 1 && names[0] === "both") {
    return ["cursor", "codex"];
  }

  const unique = [...new Set(names)];
  if (
    unique.length === 0 ||
    unique.some((name) => !HOSTS.has(name)) ||
    unique.length !== names.length
  ) {
    throw new Error(
      "Invalid --hosts. Expected cursor, codex, or both without duplicates.",
    );
  }

  return [...HOSTS].filter((name) => unique.includes(name));
};

const parseArguments = (argv) => {
  let target = process.cwd();
  let hostsValue;

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--target") {
      target = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument === "--hosts") {
      hostsValue = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument === "--help" || argument === "-h") {
      return { help: true };
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  if (typeof target !== "string" || target.trim().length === 0) {
    throw new Error("Missing target repository path.");
  }

  return {
    help: false,
    target: resolve(target),
    hosts: normalizeHostList(hostsValue),
  };
};

const usage = () =>
  [
    "Usage: node hooks/generate-project-hooks.mjs --hosts <cursor|codex|both|cursor,codex> [--target <repository>]",
    "",
    "The --hosts value is an internal value supplied after interactive host selection.",
  ].join("\n");

const runGit = (directory, args) =>
  execFileSync("git", ["-C", directory, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();

const resolveRepositoryRoot = (target) => {
  const absoluteTarget = resolve(target);
  try {
    return resolve(runGit(absoluteTarget, ["rev-parse", "--show-toplevel"]));
  } catch {
    throw new Error(`Target is not a readable Git repository: ${absoluteTarget}`);
  }
};

const readJson = async (path) =>
  JSON.parse(await readFile(path, "utf8"));

const readOptional = async (path) => {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
};

const isRegularFile = async (path) => {
  try {
    return (await stat(path)).isFile();
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
};

const copyWithHeader = (source) => {
  const text = source.toString("utf8");
  return `${GENERATED_HEADER}\n// source-sha256: ${sha256(source)}\n\n${text}`;
};

const generatedReadme = ({ host, configHash, pluginVersion }) =>
  [
    `<!-- CromeSDK generated by generate-project-hooks; host=${host}; config-sha256=${configHash}; plugin-version=${pluginVersion} -->`,
    "# Generated project hooks",
    "",
    `This directory contains the ${host} project-hook projection generated by the CromeSDK GitHub plugin.`,
    "Do not edit these files directly. Re-run `generate-project-hooks` after updating the plugin.",
    "",
    "The hook checkers are deterministic and fail closed for the protected GitHub operations when their current local gate snapshot is missing, stale, or mismatched.",
    "",
    "Gate snapshots are runtime state and remain local-only. They are written by the owning workflow immediately before its operation and must never be generated as empty or placeholder JSON.",
    "",
  ].join("\n");

const generatedAgentsBlock = ({ hosts }) => {
  const stateHosts = ["cursor", ...hosts.filter((host) => host === "codex")];
  const hostNames = hosts.map((host) => host[0].toUpperCase() + host.slice(1));
  const hostText =
    hostNames.length === 2
      ? `${hostNames[0]} and ${hostNames[1]}`
      : hostNames[0];
  const statePaths = stateHosts
    .map((host) => `\`${STATE_PATHS[host]}\``)
    .join(" and ");

  return [
    GENERATED_BLOCK_START,
    "## CromeSDK GitHub project hooks",
    "",
    `This repository contains generated ${hostText} project-hook projections from the CromeSDK GitHub plugin.`,
    `The generated checkers are deterministic and fail closed before protected GitHub operations when the current local gate snapshot is missing, stale, or mismatched.`,
    `Runtime gate state under ${statePaths} is local-only. The owning workflow writes the exact gate snapshot immediately before its operation; this generator never creates valid, empty, or placeholder gate JSON.`,
    "Regenerate the selected host projections through the `generate-project-hooks` Skill. Review and trust project hooks in the corresponding host before relying on them.",
    GENERATED_BLOCK_END,
  ].join("\n");
};

const replaceMarkedBlock = (source, replacement, start, end) => {
  const startIndex = source.indexOf(start);
  const endIndex = source.indexOf(end);
  if ((startIndex === -1) !== (endIndex === -1)) {
    throw new Error("Generated AGENTS.md block markers are incomplete.");
  }
  if (startIndex !== -1 && endIndex < startIndex) {
    throw new Error("Generated AGENTS.md block markers are out of order.");
  }
  if (startIndex !== -1) {
    const afterEnd = endIndex + end.length;
    return `${source.slice(0, startIndex)}${replacement}${source.slice(afterEnd)}`;
  }
  const separator = source.length === 0 ? "" : source.endsWith("\n") ? "\n" : "\n\n";
  return `${source}${separator}${replacement}\n`;
};

const mergeGitignore = (source, hosts) => {
  const original = source ?? "";
  const newline = original.includes("\r\n") ? "\r\n" : "\n";
  const lines = original.split(/\r?\n/);
  const additions = [];
  const stateHosts = ["cursor", ...hosts.filter((host) => host === "codex")];

  for (const host of stateHosts) {
    const statePath = STATE_PATHS[host];
    if (!lines.some((line) => line.trim() === statePath)) {
      additions.push(statePath);
    }
  }

  if (additions.length === 0) return original;
  const linePrefix =
    original.length === 0
      ? ""
      : original.endsWith("\n") || original.endsWith("\r")
        ? ""
        : newline;
  const marker =
    lines.some((line) => line.trim() === "# CromeSDK generated GitHub hook state")
      ? ""
      : `${linePrefix}# CromeSDK generated GitHub hook state${newline}`;
  const separator =
    marker.length === 0 && linePrefix.length === 0 && original.length > 0
      ? newline
      : "";
  return `${original}${linePrefix}${marker}${separator}${additions.join(newline)}${newline}`;
};

const transformCommand = (command, host, windows = false) => {
  if (typeof command !== "string") return command;
  if (host === "cursor") {
    const transformed = command.replace(
      /(\bnode\s+)["']?\.\/hooks\//,
      "$1.cursor/hooks/",
    );
    if (transformed === command || transformed.includes("./hooks/")) {
      throw new Error(`Unsupported Cursor hook command: ${command}`);
    }
    return transformed;
  }

  const transformed = windows
    ? command.replace(/%PLUGIN_ROOT%\\hooks\\/g, ".codex\\hooks\\")
    : command.replace(/\$PLUGIN_ROOT\/hooks\//g, ".codex/hooks/");
  if (
    transformed === command ||
    transformed.includes("PLUGIN_ROOT") ||
    !transformed.includes(windows ? ".codex\\hooks\\" : ".codex/hooks/")
  ) {
    throw new Error(`Unsupported Codex hook command: ${command}`);
  }
  return transformed;
};

const transformCursorConfig = (source) => {
  const result = structuredClone(source);
  for (const definitions of Object.values(result.hooks ?? {})) {
    if (!Array.isArray(definitions)) {
      throw new Error("Cursor hook configuration contains an invalid event list.");
    }
    for (const definition of definitions) {
      if (!isRecord(definition)) {
        throw new Error("Cursor hook configuration contains an invalid hook.");
      }
      definition.command = transformCommand(definition.command, "cursor");
    }
  }
  return result;
};

const transformCodexConfig = (source) => {
  const result = structuredClone(source);
  for (const groups of Object.values(result.hooks ?? {})) {
    if (!Array.isArray(groups)) {
      throw new Error("Codex hook configuration contains an invalid event list.");
    }
    for (const group of groups) {
      if (!isRecord(group) || !Array.isArray(group.hooks)) {
        throw new Error("Codex hook configuration contains an invalid matcher group.");
      }
      for (const hook of group.hooks) {
        if (!isRecord(hook)) {
          throw new Error("Codex hook configuration contains an invalid hook.");
        }
        hook.command = transformCommand(hook.command, "codex");
        if (typeof hook.commandWindows === "string") {
          hook.commandWindows = transformCommand(
            hook.commandWindows,
            "codex",
            true,
          );
        }
      }
    }
  }
  return result;
};

const output = (path, contents, options = {}) => ({
  path,
  contents,
  ...options,
});

const inspectOutput = async ({
  path,
  contents,
  replaceIfGenerated = false,
  generatedPrefix = GENERATED_HEADER,
}) => {
  const exists = await isRegularFile(path);
  if (!exists) {
    try {
      await stat(path);
      return {
        status: "blocked",
        reason: "path exists but is not a regular file",
      };
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      return { status: "write" };
    }
  }

  const current = await readFile(path);
  if (current.equals(contents)) return { status: "unchanged" };
  if (
    replaceIfGenerated &&
    current.toString("utf8").startsWith(generatedPrefix)
  ) {
    return { status: "write" };
  }
  return {
    status: "blocked",
    reason: "existing file differs from the generated projection",
  };
};

const readPluginVersion = async () => {
  const manifest = await readJson(join(PLUGIN_ROOT, "plugin.json"));
  return typeof manifest.version === "string" ? manifest.version : "unknown";
};

const createHostOutputs = async ({ repositoryRoot, host, pluginVersion }) => {
  const hostRoot = join(repositoryRoot, `.${host}`, "hooks");
  const sourceConfigPath = join(
    HOOKS_DIRECTORY,
    host === "cursor" ? "cursor-hooks.json" : "codex-hooks.json",
  );
  const sourceConfig = await readJson(sourceConfigPath);
  const generatedConfig =
    host === "cursor"
      ? transformCursorConfig(sourceConfig)
      : transformCodexConfig(sourceConfig);
  const configContents = Buffer.from(
    `${JSON.stringify(generatedConfig, null, 2)}\n`,
    "utf8",
  );
  const configPath = join(repositoryRoot, `.${host}`, "hooks.json");
  const readmePath = join(hostRoot, "README.md");
  const readmeContents = generatedReadme({
    host,
    configHash: sha256(configContents),
    pluginVersion,
  });
  const files = [
    output(configPath, configContents),
    output(readmePath, Buffer.from(readmeContents, "utf8"), {
      replaceIfGenerated: true,
      generatedPrefix: "<!-- CromeSDK generated by generate-project-hooks;",
    }),
  ];

  for (const relativePath of [...CHECKER_FILES, ...HELPER_FILES]) {
    const source = await readFile(join(HOOKS_DIRECTORY, relativePath));
    files.push(
      output(
        join(hostRoot, relativePath),
        Buffer.from(copyWithHeader(source), "utf8"),
        { replaceIfGenerated: true },
      ),
    );
  }

  return {
    host,
    configPath,
    configContents,
    readmePath,
    files,
  };
};

const inspectConfigAgainstPreviousProjection = async ({
  hostOutput,
  existingReadme,
}) => {
  const configPath = hostOutput.configPath;
  const configContents = hostOutput.configContents;
  const configInspection = await inspectOutput({
    path: configPath,
    contents: configContents,
  });
  if (configInspection.status !== "blocked") return configInspection;
  const previousHash = existingReadme?.match(
    /config-sha256=([a-f0-9]{64})\b/i,
  )?.[1];
  if (
    previousHash &&
    (await isRegularFile(configPath)) &&
    previousHash === sha256(await readFile(configPath))
  ) {
    return { status: "write" };
  }
  return configInspection;
};

const generateProjectHooks = async ({ target, hosts }) => {
  const normalizedHosts = normalizeHostList(hosts.join(","));
  const repositoryRoot = resolveRepositoryRoot(target);
  const pluginVersion = await readPluginVersion();
  const hostOutputs = await Promise.all(
    normalizedHosts.map((host) =>
      createHostOutputs({ repositoryRoot, host, pluginVersion }),
    ),
  );

  const existingReadmes = new Map();
  for (const hostOutput of hostOutputs) {
    existingReadmes.set(
      hostOutput.host,
      await readOptional(hostOutput.readmePath),
    );
  }

  const operations = [];
  const blocked = [];
  for (const hostOutput of hostOutputs) {
    for (const file of hostOutput.files) {
      const inspection =
        file.path === hostOutput.configPath
          ? await inspectConfigAgainstPreviousProjection({
              hostOutput,
              existingReadme: existingReadmes.get(hostOutput.host),
            })
          : await inspectOutput(file);
      if (inspection.status === "blocked") {
        blocked.push({ path: file.path, reason: inspection.reason });
      } else {
        operations.push({ ...file, status: inspection.status });
      }
    }
  }

  const gitignorePath = join(repositoryRoot, ".gitignore");
  const gitignore = await readOptional(gitignorePath);
  const mergedGitignore = mergeGitignore(gitignore, normalizedHosts);
  if (mergedGitignore !== (gitignore ?? "")) {
    operations.push({
      path: gitignorePath,
      contents: Buffer.from(mergedGitignore, "utf8"),
      status: "write",
    });
  }

  const agentsPath = join(repositoryRoot, "AGENTS.md");
  const agentsSource = (await readOptional(agentsPath)) ?? "";
  let mergedAgents;
  try {
    mergedAgents = replaceMarkedBlock(
      agentsSource,
      generatedAgentsBlock({ hosts: normalizedHosts }),
      GENERATED_BLOCK_START,
      GENERATED_BLOCK_END,
    );
  } catch (error) {
    blocked.push({ path: agentsPath, reason: error.message });
    mergedAgents = agentsSource;
  }
  if (mergedAgents !== agentsSource) {
    operations.push({
      path: agentsPath,
      contents: Buffer.from(mergedAgents, "utf8"),
      status: "write",
    });
  }

  if (blocked.length > 0) {
    return {
      status: "blocked",
      target: repositoryRoot,
      hosts: normalizedHosts,
      plugin_version: pluginVersion,
      written_paths: [],
      unchanged_paths: operations
        .filter((operation) => operation.status === "unchanged")
        .map((operation) => operation.path),
      blocked,
      limitations: [
        "No files were written because one or more existing paths conflict with the requested projection.",
      ],
    };
  }

  const writtenPaths = [];
  const unchangedPaths = [];
  try {
    for (const operation of operations) {
      if (operation.status === "unchanged") {
        unchangedPaths.push(operation.path);
        continue;
      }
      await mkdir(dirname(operation.path), { recursive: true });
      await writeFile(operation.path, operation.contents, { flag: "w" });
      writtenPaths.push(operation.path);
    }
  } catch (error) {
    return {
      status: "partial",
      target: repositoryRoot,
      hosts: normalizedHosts,
      plugin_version: pluginVersion,
      written_paths: writtenPaths,
      unchanged_paths: unchangedPaths,
      blocked: [
        {
          path: error.path ?? repositoryRoot,
          reason: "A generated file could not be written.",
        },
      ],
      limitations: [
        "The write stopped after an I/O failure; inspect the listed paths before retrying.",
      ],
    };
  }

  return {
    status: writtenPaths.length > 0 ? "written" : "unchanged",
    target: repositoryRoot,
    hosts: normalizedHosts,
    plugin_version: pluginVersion,
    written_paths: writtenPaths,
    unchanged_paths: unchangedPaths,
    blocked: [],
    limitations: normalizedHosts.includes("codex")
      ? [
          "Codex project hooks require a trusted project and explicit hook review/trust before they run.",
        ]
      : [],
  };
};

const main = async () => {
  const argumentsValue = parseArguments(process.argv.slice(2));
  if (argumentsValue.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }
  const result = await generateProjectHooks(argumentsValue);
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  if (result.status === "blocked" || result.status === "partial") {
    process.exitCode = 2;
  }
};

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stdout.write(
      `${JSON.stringify(
        {
          status: "failed",
          hosts: [],
          written_paths: [],
          unchanged_paths: [],
          blocked: [
            {
              path: null,
              reason: error instanceof Error ? error.message : "Generation failed.",
            },
          ],
          limitations: ["No projection was completed."],
        },
        null,
        2,
      )}\n`,
    );
    process.exitCode = 1;
  });
}

